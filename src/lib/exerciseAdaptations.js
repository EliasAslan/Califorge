const normalizeEquipment = (item) => {
  const key = String(item || '').trim().toLowerCase();
  if (!key || key === 'floor' || key === 'bodyweight') return null;
  return EQUIPMENT_ALIASES[key] || item;
};

export const normalizeEquipmentInventory = (equipment = []) =>
  new Set((Array.isArray(equipment) ? equipment : []).map(normalizeEquipment).filter(Boolean));

export const isExerciseEquipmentAvailable = (exerciseId, equipment = []) => {
  const rule = EQUIPMENT_REQUIREMENTS[exerciseId];
  if (!rule) return true;
  const inventory = normalizeEquipmentInventory(equipment);
  if ((rule.all || []).some((item) => !inventory.has(normalizeEquipment(item)))) return false;
  if (rule.any?.length && !rule.any.some((item) => inventory.has(normalizeEquipment(item)))) return false;
  return true;
};

